// Copies the CSS and client script from lib/render.js into the Python package
// so both channels ship the same page chrome. Run from the repo root:
//   node python/scripts/sync_assets.js
const fs = require("fs");
const path = require("path");
const Module = require("module");
const src = path.join(__dirname, "..", "..", "lib", "render.js");
const code = fs.readFileSync(src, "utf8") + "\nmodule.exports.__assets = { CSS_VARS, CSS, SCRIPT };\n";
const m = new Module(src);
m.filename = src;
m.paths = Module._nodeModulePaths(path.dirname(src));
m._compile(code, src);
const a = m.exports.__assets;
const out =
  '"""Page chrome shared with lib/render.js. Generated by python/scripts/sync_assets.js; do not edit."""\n' +
  "CSS_VARS = " + JSON.stringify(a.CSS_VARS) + "\n" +
  "CSS = " + JSON.stringify(a.CSS) + "\n" +
  "SCRIPT = " + JSON.stringify(a.SCRIPT) + "\n";
fs.writeFileSync(path.join(__dirname, "..", "src", "bucket_list", "_assets.py"), out);
console.log("wrote _assets.py");
